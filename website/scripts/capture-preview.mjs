import { chromium } from "playwright";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
const root = fileURLToPath(new URL("../", import.meta.url));
const qa = path.join(root, "qa");
await mkdir(qa, { recursive: true });
const browser = await chromium.launch({ channel: "msedge", headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1536, height: 1024 }, reducedMotion: "reduce" });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.goto("http://127.0.0.1:4173/", { waitUntil: "networkidle" });
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: path.join(qa, "home-desktop.png") });
  await page.screenshot({ path: path.join(qa, "home-full.png"), fullPage: true });
  console.log(JSON.stringify({ errors, hero: await page.locator(".hero").boundingBox(), h1: await page.locator("h1").boundingBox() }));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.reload({ waitUntil: "networkidle" });
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: path.join(qa, "home-mobile-viewport.png") });
  await page.screenshot({ path: path.join(qa, "home-mobile.png"), fullPage: true });
  await page.goto("http://127.0.0.1:4173/product_list", { waitUntil: "networkidle" });
  await page.screenshot({ path: path.join(qa, "catalog-mobile.png"), fullPage: true });
  await page.setViewportSize({ width: 1536, height: 1024 });
  await page.screenshot({ path: path.join(qa, "catalog-desktop.png") });
  await page.goto("http://127.0.0.1:4173/p128297198-obuchenie-gost-isoiec.html", { waitUntil: "networkidle" });
  await page.screenshot({ path: path.join(qa, "service-desktop.png") });
  await page.evaluate(() => scrollTo(0, 680));
  await page.screenshot({ path: path.join(qa, "service-reading.png") });
  await page.goto("http://127.0.0.1:4173/", { waitUntil: "networkidle" });
  await page.evaluate(() => scrollTo(0, 1100));
  await page.screenshot({ path: path.join(qa, "home-sections.png") });
  const reference = await readFile(path.resolve(root, "../output/design-concepts-round-3/03-technological.png"));
  const implementation = await readFile(path.join(qa, "home-desktop.png"));
  const comparison = `<!doctype html><html><head><meta charset="utf-8"><title>Visual comparison</title></head><body style="margin:0;background:#ddd;font:16px Arial"><div style="display:grid;grid-template-columns:1fr 1fr;gap:2px"><div><p style="padding:0 16px">Выбранный макет · 1536 × 1024</p><img style="width:100%;display:block" src="data:image/png;base64,${reference.toString("base64")}"></div><div><p style="padding:0 16px">Реализация · 1536 × 1024</p><img style="width:100%;display:block" src="data:image/png;base64,${implementation.toString("base64")}"></div></div></body></html>`;
  await writeFile(path.join(qa, "comparison.html"), comparison);
  await page.setContent(comparison);
  await page.screenshot({ path: path.join(qa, "comparison.png"), fullPage: true });
} finally { await browser.close(); }
