async function main() {
  await access(path.join(outputRoot, "index.html")).catch(() => {
    throw new Error("dist/client/index.html is missing. Run the Vite production build first.");
  });
  const source = JSON.parse(await readFile(sourcePath, "utf8"));
  if (!Array.isArray(source.pages) || source.pages.length === 0) {
    throw new Error("site-data.json must contain a non-empty pages array.");
  }
  const pages = source.pages.map((sourcePage) => ({
    ...sourcePage,
    path: validateRoute(sourcePage.path),
  }));
  if (new Set(pages.map((item) => item.path)).size !== pages.length) {
    throw new Error("Duplicate source paths found; refusing to overwrite a page.");
  }
  if (!pages.some((item) => item.path === "/")) {
    throw new Error("The source does not contain the homepage.");
  }
  // Validate all destinations before starting a browser.
  for (const item of pages) outputPath(item.path);
  const builtHtml = await readFile(path.join(outputRoot, "index.html"), "utf8");
  const { chromium } = await loadPlaywright();
  let server;
  let browser;
  const rendered = [];
  let cursor = 0;
  try {
    server = await preview({
      root: projectRoot,
      logLevel: "error",
      preview: { host: "127.0.0.1", port: 0, open: false },
    });
    const address = server.httpServer.address();
    if (!address || typeof address === "string") throw new Error("No Vite preview port.");
    const previewOrigin = `http://127.0.0.1:${address.port}`;
    const launchOptions = { headless: true };
    if (process.env.PRERENDER_BROWSER_EXECUTABLE) {
      launchOptions.executablePath = process.env.PRERENDER_BROWSER_EXECUTABLE;
    } else if (process.env.PRERENDER_BROWSER_CHANNEL) {
      launchOptions.channel = process.env.PRERENDER_BROWSER_CHANNEL;
    } else if (process.platform === "win32") {
      launchOptions.channel = "msedge";
    }
    browser = await chromium.launch(launchOptions);
    const context = await browser.newContext({
      viewport: { width: 1440, height: 1000 },
      locale: "ru-RU",
      reducedMotion: "reduce",
      serviceWorkers: "block",
    });
    const parserPage = await context.newPage();
    // DOMParser removes only root content, so rerunning this script against a
    // previously prerendered build also starts from an empty React root.
    const shellHtml = await parserPage.evaluate((html) => {
      const document = new DOMParser().parseFromString(html, "text/html");
      const root = document.getElementById("root");
      if (!root) throw new Error("Built HTML has no #root element.");
      root.replaceChildren();
      document.querySelectorAll(
        "link[rel='canonical'], meta[property='og:title'], meta[property='og:description'], " +
        "meta[property='og:url'], meta[name='twitter:title'], meta[name='twitter:description']",
      )
        .forEach((element) => element.remove());
      document.querySelectorAll("meta[name='description']").forEach((element) => element.remove());
      document.title = "";
      return `<!doctype html>\n${document.documentElement.outerHTML}`;
    }, builtHtml);
    await parserPage.close();

    async function renderWorker() {
      const page = await context.newPage();
      const runtimeErrors = [];
      const failedAssets = [];
      page.on("pageerror", (error) => runtimeErrors.push(error.message));
      page.on("response", (response) => {
        if (
          response.url().startsWith(previewOrigin) &&
          response.status() >= 400 &&
          ["script", "stylesheet", "font"].includes(response.request().resourceType())
        ) {
          failedAssets.push(`${response.status()} ${response.url()}`);
        }
      });
      await page.route("**/*", async (route) => {
        const request = route.request();
        // Serve the same empty production shell at each exact old URL. This
        // avoids preview-server slash redirects and previously written HTML.
        if (request.isNavigationRequest() && request.frame() === page.mainFrame()) {
          await route.fulfill({ status: 200, contentType: "text/html; charset=utf-8", body: shellHtml });
        } else if (!request.url().startsWith(previewOrigin)) {
          // Rendering must not rely on third-party embeds, analytics or network.
          await route.abort();
        } else {
          await route.continue();
        }
      });
      try {
        while (cursor < pages.length) {
          const sourcePage = pages[cursor++];
          runtimeErrors.length = 0;
          failedAssets.length = 0;
          await page.goto(`${previewOrigin}${sourcePage.path}`, {
            waitUntil: "domcontentloaded",
            timeout: 30000,
          });
          await page.waitForFunction(
            () => document.querySelector("#root main h1")?.textContent.trim(),
            null,
            { timeout: 15000 },
          );
          await page.evaluate(async () => {
            await Promise.race([
              document.fonts.ready,
              new Promise((_, reject) => setTimeout(() => reject(new Error("Fonts did not settle.")), 15000)),
            ]);
            await new Promise((resolve) => requestAnimationFrame(() => requestAnimationFrame(resolve)));
          });
          if (runtimeErrors.length || failedAssets.length) {
            throw new Error(
              `Prerender failed on ${sourcePage.path}:\n${[...runtimeErrors, ...failedAssets].join("\n")}`,
            );
          }
          const metadata = pageMetadata(sourcePage);
          const snapshot = await page.evaluate(({ metadata, expectedPath }) => {
            if (location.pathname !== expectedPath) {
              throw new Error(`Unexpected route: ${location.pathname}, expected ${expectedPath}`);
            }
            const main = document.querySelector("#root main");
            if (!main || main.innerText.trim().length < 40) {
              throw new Error(`Main content is missing or empty on ${expectedPath}`);
            }
            document.documentElement.lang = "ru";
            // Prefer route-specific metadata already produced by the app.
            const existingCanonical = document.querySelector("link[rel='canonical']");
            const routeMetadataReady = existingCanonical?.href === metadata.canonical;
            if (!routeMetadataReady || !document.title.trim()) document.title = metadata.title;
            const setMeta = (selector, attributes) => {
              const matches = [...document.querySelectorAll(selector)];
              const element = matches.shift() || document.createElement("meta");
              matches.forEach((duplicate) => duplicate.remove());
              Object.entries(attributes).forEach(([key, value]) => element.setAttribute(key, value));
              if (!element.parentNode) document.head.append(element);
              return element;
            };
            const currentDescription = document.querySelector("meta[name='description']")?.content;
            const description = routeMetadataReady && currentDescription?.trim()
              ? currentDescription
              : metadata.description;
            setMeta("meta[name='description']", { name: "description", content: description });
            let canonical = existingCanonical;
            if (!canonical) {
              canonical = document.createElement("link");
              canonical.rel = "canonical";
              document.head.append(canonical);
            }
            canonical.href = metadata.canonical;
            document.querySelectorAll("link[rel='canonical']").forEach((element) => {
              if (element !== canonical) element.remove();
            });
            setMeta("meta[property='og:title']", { property: "og:title", content: document.title });
            setMeta("meta[property='og:description']", { property: "og:description", content: description });
            setMeta("meta[property='og:url']", { property: "og:url", content: metadata.canonical });
            setMeta("meta[property='og:type']", { property: "og:type", content: "website" });
            setMeta("meta[property='og:site_name']", { property: "og:site_name", content: "КазПроф Лаб" });
            setMeta("meta[property='og:locale']", { property: "og:locale", content: "ru_KZ" });
            // Keep Vite's valid modulepreloads and CSS links. Runtime image
            // preloads are harmless, but remove only accidental local-preview URLs.
            document.querySelectorAll("link[rel='preload'], link[rel='modulepreload']")
              .forEach((element) => {
                const href = element.getAttribute("href");
                if (href?.startsWith(location.origin)) {
                  element.setAttribute("href", href.slice(location.origin.length));
                }
              });
            // HTML serialization otherwise merges adjacent React text nodes
            // (for example "© ", year, company name), causing hydration #418.
            // Preserve those boundaries with the same kind of inert separator
            // React's server renderer emits. Work on a clone, not React's DOM.
            const snapshotDocument = document.documentElement.cloneNode(true);
            const walker = document.createTreeWalker(
              snapshotDocument.querySelector("#root"),
              NodeFilter.SHOW_TEXT,
            );
            const textNodes = [];
            while (walker.nextNode()) textNodes.push(walker.currentNode);
            for (const node of textNodes) {
              if (node.previousSibling?.nodeType === Node.TEXT_NODE) {
                node.parentNode.insertBefore(document.createComment(" "), node);
              }
            }
            return {
              html: `<!doctype html>\n${snapshotDocument.outerHTML}\n`,
              title: document.title,
              description,
              h1: main.querySelector("h1")?.textContent.trim(),
              characters: main.innerText.trim().length,
            };
          }, { metadata, expectedPath: sourcePage.path });
          rendered.push({ path: sourcePage.path, ...snapshot });
          console.log(`[${rendered.length}/${pages.length}] ${sourcePage.path}`);
        }
      } finally {
        await page.close();
      }
    }
    const results = await Promise.allSettled(
      Array.from({ length: Math.min(workerCount, pages.length) }, () => renderWorker()),
    );
    const failures = results.filter((result) => result.status === "rejected");
    if (failures.length) throw new AggregateError(failures.map((result) => result.reason), "Prerender failed.");
  } finally {
    // Close both even when a navigation, asset, or browser startup fails.
    await Promise.allSettled([browser?.close(), server?.close()]);
  }

  if (rendered.length !== pages.length) throw new Error("Prerender did not produce every source page.");
  // No HTML output is changed until the complete rendering pass succeeds.
  for (const item of rendered) {
    const target = outputPath(item.path);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, item.html, "utf8");
  }
  const urls = pages.map((item) => `  <url><loc>${escapeXml(new URL(item.path, siteOrigin).href)}</loc></url>`);
  await Promise.all([
    writeFile(
      path.join(outputRoot, "sitemap.xml"),
      `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`,
      "utf8",
    ),
    writeFile(path.join(outputRoot, "robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${siteOrigin}/sitemap.xml\n`, "utf8"),
    writeFile(path.join(outputRoot, ".htaccess"), apacheConfig, "utf8"),
    writeFile(path.join(outputRoot, "404.html"), notFoundHtml(), "utf8"),
    writeFile(
      path.join(projectRoot, "dist", "prerender-manifest.json"),
      JSON.stringify({
        siteOrigin,
        generatedAt: new Date().toISOString(),
        pageCount: rendered.length,
        pages: rendered.map(({ html, ...entry }) => entry).sort((a, b) => a.path.localeCompare(b.path)),
      }, null, 2) + "\n",
      "utf8",
    ),
  ]);
  console.log(`Prerendered ${rendered.length} source pages into ${outputRoot}`);
  console.log("Generated sitemap.xml, robots.txt, .htaccess, 404.html and dist/prerender-manifest.json.");
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
