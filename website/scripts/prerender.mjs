#!/usr/bin/env node
import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { preview } from "vite";

// Run after vite build. Paths are relative to this file, never to the caller's cwd.
const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputRoot = path.join(projectRoot, "dist", "client");
const sourcePath = path.join(projectRoot, "src", "data", "site-data.json");
const require = createRequire(import.meta.url);
const siteOrigin = new URL(process.env.SITE_URL || "https://kazproflab.kz").origin;
const workerCount = Math.min(6, Math.max(1, Number(process.env.PRERENDER_WORKERS) || 3));

async function loadPlaywright() {
  try {
    return require("playwright");
  } catch (error) {
    if (error.code !== "MODULE_NOT_FOUND") throw error;
  }
  // Optional fallback for this workstation; a normal installation uses the
  // project's Playwright devDependency. Set PLAYWRIGHT_PACKAGE_PATH elsewhere.
  const fallback =
    process.env.PLAYWRIGHT_PACKAGE_PATH ||
    (process.env.LOCALAPPDATA &&
      path.join(
        process.env.LOCALAPPDATA,
        "npm-cache",
        "_npx",
        "d0a7a686d16af82b",
        "node_modules",
        "playwright",
      ));
  if (fallback) {
    try {
      return require(path.resolve(fallback));
    } catch (error) {
      if (error.code !== "MODULE_NOT_FOUND") throw error;
    }
  }
  throw new Error(
    "Playwright is required for prerendering. Install the project's devDependencies, " +
      "or set PLAYWRIGHT_PACKAGE_PATH to an existing playwright package.",
  );
}

function validateRoute(route) {
  if (
    typeof route !== "string" ||
    !route.startsWith("/") ||
    route.startsWith("//") ||
    /[\\?#%\0]/.test(route) ||
    route.split("/").some((part) => part === "." || part === "..") ||
    (route !== "/" && route.endsWith("/"))
  ) {
    throw new Error(`Invalid canonical source path: ${JSON.stringify(route)}`);
  }
  return route;
}

function outputPath(route) {
  const relative = route === "/" ? "index.html" : route.slice(1);
  const filename = route === "/" || relative.endsWith(".html")
    ? relative
    : path.join(relative, "index.html");
  const target = path.resolve(outputRoot, filename);
  const relativeTarget = path.relative(outputRoot, target);
  if (relativeTarget.startsWith("..") || path.isAbsolute(relativeTarget)) {
    throw new Error(`Output path escapes dist/client: ${route}`);
  }
  return target;
}

function plainText(value) {
  return String(value || "")
    .replace(/<[^>]*>/g, " ")
    .replace(/&nbsp;/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function shortDescription(value) {
  const text = plainText(value);
  if (text.length <= 175) return text;
  const segment = text.slice(0, 172);
  const boundary = segment.lastIndexOf(" ");
  return `${segment.slice(0, boundary > 120 ? boundary : segment.length).trimEnd()}…`;
}

function pageMetadata(sourcePage) {
  const isHome = sourcePage.path === "/";
  return {
    title: isHome
      ? "КазПроф Лаб — обучение, аудит и сопровождение лабораторий"
      : `${plainText(sourcePage.title)} | КазПроф Лаб`,
    description: shortDescription(
      isHome
        ? "Обучение специалистов, аудит, подготовка лабораторий к аккредитации и внедрение систем менеджмента. КазПроф Лаб, Астана. Работаем с организациями Казахстана."
        : sourcePage.description || sourcePage.text || sourcePage.title,
    ),
    canonical: new URL(sourcePage.path, siteOrigin).href,
  };
}

function escapeXml(value) {
  return String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

const apacheConfig = `# Generated by scripts/prerender.mjs. Apache 2.4, mod_rewrite.
# Upload this hidden file together with all of dist/client.
Options -Indexes -MultiViews
DirectoryIndex index.html
DirectorySlash Off
AddDefaultCharset UTF-8
ErrorDocument 404 /404.html

RewriteEngine On

# Keep the original extensionless URLs canonical (without a trailing slash).
RewriteCond %{REQUEST_FILENAME}/index.html -f
RewriteRule ^(.+)/$ /$1 [R=301,L,NE]

# Serve existing assets and exact .html product URLs.
RewriteCond %{REQUEST_FILENAME} -f
RewriteRule ^ - [END]

# Resolve extensionless source addresses without a browser redirect.
RewriteCond %{REQUEST_FILENAME}/index.html -f
RewriteRule ^(.+?)/?$ $1/index.html [END]
RewriteRule ^$ index.html [END]

# An unknown address must be a genuine 404, not a copy of the homepage.
RewriteRule ^ - [R=404,L]

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  <FilesMatch "\\.html$">
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>
`;

